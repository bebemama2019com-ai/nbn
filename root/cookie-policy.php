<p><strong>КАК  ИЗПОЛЗВАМЕ БИСКВИТКИТЕ </strong></p>
<p>Нашият  сайт предлага функционалности и  инструменти, които са на разположение  само при използване на някои от видовете  бисквитки. Винаги е възможно да блокирате,  изтриете или деактивирате тези бисквитки,  но имайте предвид, че ако го направите  най-вероятно няма да имате възможност  да използвате този сайт пълноценно. </p>
<p><strong>КАКВО  НЕ МОГАТ ДА ПРАВЯТ БИСКВИТКИТЕ </strong></p>
<p>Бисквитките  са обикновени текстови файлове. Те не  са компилирани и не могат да осъществяват  програмни функции. Не могат да проверяват  или да сканират вашия компютър, нито да  ви следят или да търсят лична информация  на вашето устройство. </p>
<p>Бисквитките  са безопасни файлове и не могат да  шпионират вашия компютър и да установяват  информация относно вас или вашето  семейство. Бисквитките единствено  позволяват на уебсайта да разпознава  завръщащите се потребители в него.</p>
<p><strong>КАК  ДА УПРАВЛЯВАМ БИСКВИТКИТЕ, СЪХРАНЯВАНИ  В МОЕТО УСТРОЙСТВО </strong></p>
<p>Бисквитките  могат да бъда деактивирани или премахнати  с инструменти, които са налични в повечето  съвременни браузъри. Настройките на  всеки браузър са индивидуални и всеки  браузър предлага различни функционалности  и възможности за управление. За повече  информация как можете да блокирате,  изтриете или деактивирате бисквитки,  моля, прегледайте настройките на вашия  браузъра или устройство. </p>
