<p>За  да направим посещението на нашата  страница атрактивно и за да бъде възможно  използването на определени функции,  ние използваме така наречените &bdquo;бисквитки&ldquo;  (<span lang="en-US" xml:lang="en-US">c</span>ookies<span lang="en-US" xml:lang="en-US">).</span></p>
<p><strong>КАКВО  Е БИСКВИТКА </strong><span lang="en-US" xml:lang="en-US"><strong>(COOKIE)</strong></span></p>
<p>Бисквитките  са малки файлове с текстово съдържание  и уникален номер, които се съхраняват  в директорията на браузъра навашия  компютър. Те се създават, когато използвате  вашия браузър и посетите уебсайт, който  използва бисквитки. Основната им функция  е да следят вашето движение в сайта,  като ви помагат да се върнете към  последното състояние, в което сте го  използвали, могат да помнят вашите  потребителско име и парола, избор на  тема, избрани предпочитания или други  функции по персонализация. Уебсайтът  съхранява запис (със същия уникален  номер като съответната бисквитка) към  този, настроен по-рано от него във вашия  браузър. Чрез този запис бисквитките  могат да проследяват и съхраняват  информация относно вашето преживяване  в сайта.</p>
<p>Бисквитките  често са крайно необходими за уебсайтове,  които имат големи бази данни, изискват  регистрация или ползване на потребителски  профил, предоставят възможности за  персонализация на изгледа и други.</p>
<p>Обичайно  бисквитките съдържат малко информация  като интернет адреса на уебсайта, който  ги е създал, валидността им и техния  номер. Поради малкия обем информация,  който съдържат, бисквитките обичайно  не могат да бъдат използвани за разкриване  на вашата самоличност или на лична  информация. </p>
<p><strong>КАКВИ  ВИДОВЕ БИСКВИТКИ ИМА И ЗА КАКВО СЕ  ИЗПОЛЗВАТ </strong></p>
<p><strong>Сесийни  бисквитки </strong></p>
<p>Те  се използват например в уебсайтове за  електронна търговия, така че потребителите  да могат свободно да продължат да  сърфират без да губят продуктите, които  са поставили в кошницата. Сесийните  бисквитки помагат също да се подобри  времето за зареждане на сайта. Изтриват  се, когато затворите браузъра си. </p>
<p><strong>Постоянни  бисквитки </strong></p>
<p>Те  не губят своята валидност, когато  браузърът се затвори. Срокът им на  валидност може да варира, но обикновено  не е по-дълъг от 6 месеца.  Използват се,  за да съхраняват например вашите данни  за достъп, така че да не е необходимо да  ги въвеждате всеки път. Освен това могат  да се използват за персонализация и да  съхраняват предпочитанията на  посетителите, като например избран език  или валута. </p>
<p><strong>Бисквитки  от доставчици на външни услуги</strong></p>
<p>Обичайно  произходът на бисквитките съответства  на наименованието (домейна) на уебсайта,  на който се намират. Това не важи за  бисквитките от доставчици на външни  услуги. При тях бисквитките се създават  от самия доставчик, който може да бъде  рекламодател например. Тези бисквитки  събират данни относно вашите навици и  интереси в интернет и могат да ви следят  през различни уебсайтове. Чрез тях е  възможно да се установи кои страници  посещавате, в каква последователност  и колко време престоявате в тях. Най-често  се използват за анализиране на посещенията  и интересите на потребителите по даден  тема.</p>
