      <p><strong>WHAT  CAN NOT COOKIES DO </strong></p>
      <p>Cookies  are plain text files. They are not compiled so they cannot execute  functions or make copies of themselves. They cannot browse through or  scan your computer or otherwise snoop on you or dig for private  information on your hard disk.</p>
      <p>Because  cookies are just harmless files, or keys, they cannot look into your  computer and find out information about you, your family, or read any  material kept on your hard-drive. Cookies simply unlock a computer's  memory and allow a website to recognise users when they return to a  site by opening doors to different content or services. </p>
