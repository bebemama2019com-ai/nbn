      <p>In  order to make thе visits to our page attractive and to use certain  features, we use so-called &bdquo;cookies&rdquo;.</p>
      <p><strong>WHAT  IS A COOKIE</strong></p>
      <p>Cookies  are usually small text files, given ID tags that are stored on your  computer's browser directory or program data subfolders. Cookies are  created when you use your browser to visit a website that uses  cookies to keep track of your movements within the site, help you  resume where you left off, remember your registered login, theme  selection, preferences, and other customization functions.The website  stores a corresponding file(with same ID tag)to the one they set in  your browser and in this file they can track and keep information on  your movements within the site and any information you may have  voluntarily given while visiting the website, such as email address.</p>
      <p>Cookies  are often indispensable for websites that have huge databases, need  logins, have customizable themes, other advanced features.</p>
      <p>Cookies  usually don't contain much information except for the url of the  website that created the cookie, the duration of the cookie's  abilities and effects, and a random number. Due to the little amount  of information a cookie contains, it usually cannot be used to reveal  your identity or personally identifying information.However,  marketing is becoming increasingly sophisticated and cookies in some  cases can be agressively used to create a profile of your surfing  habits.</p>
      <p LANG="bg-BG"><BR>
      </p>
      <p><strong>WHAT </strong><strong>ARE</strong><strong> THE</strong><strong> TYPES OF </strong><strong>COOKIES</strong><strong> AND WHAT ARE </strong><strong>THEY </strong><strong>USED</strong><strong> FOR</strong></p>
      <p><strong>Session</strong><strong> cookies</strong></p>
      <p>They are  used for example on e-commerce websites so you can continue browsing  without losing what you put in your cart. Session  cookies also help to improve site load time. They  expire when you close your browser.</p>
      <p><strong>Permanent</strong><strong> cookies</strong></p>
      <p>They  persist even when the browser is closed. They have an expiration date  though and by law, you can&rsquo;t make them last more than 6 months.  They&rsquo;re used to remember your passwords and login info so you don&rsquo;t  have to re-enter them every time. Furthermore,  it can be used for personalization and to store the preferences of  visitors, such as selected language or currency.</p>
      <p><strong>Third-party</strong><strong> cookies</strong></p>
      <p>Cookies  attributes usually corresponds to the website domain they are on. Not  for third-party cookies, they are installed by third-party websites,  such as advertisers. They gather data about your browsing habits, and  allow them to track you across multiple websites and  they can track you through different websites. Through them it is  possible to determine which pages you visit, in what order and how  long you stay in them. Most often used to analyze the visits and the  interests of consumers on a particular topic.</p>
